"""Copy reports/<name>/REPORT.md to the repository root, rewriting relative image links so they still resolve."""
import re
import sys
from pathlib import Path

name = sys.argv[1] if len(sys.argv) > 1 else "weekend"
src = Path("reports") / name / "REPORT.md"
text = src.read_text()
text = re.sub(r"\]\(((?:[A-Za-z0-9_\-]+)\.png)\)", rf"](reports/{name}/\1)", text)
header = (f"<!-- Generated by `roborobust report` from results/{name}/episode_results.jsonl and copied here by scripts/publish_report.py. "
          f"Do not edit by hand; regenerate. Full set of tables/plots: reports/{name}/ -->\n\n")
Path("REPORT.md").write_text(header + text)
print(f"wrote REPORT.md from {src}")
